-- Opcjonalna część Oracle. Uruchom w SQL Developer / SQLcl jako właściciel schematu.
-- Nie jest używana przez lokalną aplikację SQLite.

CREATE TABLE hd_tickets (
    id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    external_id VARCHAR2(64 CHAR) UNIQUE,
    title VARCHAR2(120 CHAR) NOT NULL,
    requester VARCHAR2(80 CHAR) NOT NULL,
    category VARCHAR2(20 CHAR) NOT NULL,
    priority VARCHAR2(20 CHAR) NOT NULL,
    status VARCHAR2(20 CHAR) DEFAULT 'new' NOT NULL,
    -- Oracle traktuje pusty napis jako NULL; opis jest opcjonalny.
    description VARCHAR2(1500 CHAR),
    created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT hd_category_ck CHECK (category IN ('hardware', 'software', 'access', 'other')),
    CONSTRAINT hd_priority_ck CHECK (priority IN ('low', 'normal', 'high')),
    CONSTRAINT hd_status_ck CHECK (status IN ('new', 'in_progress', 'done'))
);

CREATE INDEX hd_tickets_status_ix ON hd_tickets (status);

CREATE OR REPLACE TRIGGER hd_tickets_updated_trg
BEFORE UPDATE ON hd_tickets
FOR EACH ROW
BEGIN
    :NEW.updated_at := SYSTIMESTAMP;
END;
/

CREATE OR REPLACE PROCEDURE hd_set_status (
    p_id IN hd_tickets.id%TYPE,
    p_status IN hd_tickets.status%TYPE
) AS
BEGIN
    IF p_status IS NULL OR p_status NOT IN ('new', 'in_progress', 'done') THEN
        RAISE_APPLICATION_ERROR(-20001, 'Nieprawidlowy status zgloszenia');
    END IF;

    UPDATE hd_tickets SET status = p_status WHERE id = p_id;
    IF SQL%ROWCOUNT = 0 THEN
        RAISE_APPLICATION_ERROR(-20002, 'Nie znaleziono zgloszenia');
    END IF;
    -- Transakcję zatwierdza kod wywołujący.
END;
/

CREATE OR REPLACE VIEW hd_status_summary AS
SELECT status, COUNT(*) AS total,
       SUM(CASE WHEN priority = 'high' THEN 1 ELSE 0 END) AS high_priority
FROM hd_tickets
GROUP BY status;

